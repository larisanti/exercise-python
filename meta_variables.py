# Várias variáveis em uma linha

a = b = c = 10

print(a)
print(b)
print(c)

# Mostrou o mesmo resultado várias vezes porque recebem o mesmo valor (10)


# Mudança da variável obdece a ordem de cima pra baixo:

a = 10
print(a)
a = 5
print(a)

# Mostrou primeiro 10 e depois 5 porque foi a ordem que escolhi as variáveis

# Deletar a variável:

a = 10

